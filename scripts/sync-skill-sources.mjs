#!/usr/bin/env node
// Generate src/editor/skill-atlas/skillSources.generated.ts from
// .claude/skills so the atlas's source pane shows the text Claude actually
// loads, not a raw import across the package boundary (see
// docs/docs-loading-bug.md — import.meta.glob and a relative ?raw import both
// break in a tarball consumer's pre-bundled node_modules). A plain ES module
// of string literals has no such dependency. Mirrors sync-docs.mjs.
//
//   node scripts/sync-skill-sources.mjs [--write|--check]
//
// --write (re)generates the file; --check (CI gate) exits 1 on drift; the
// default is a dry run that reports whether the file is current.

import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SKILLS = join(ROOT, '.claude/skills');
const OUT = join(ROOT, 'src/editor/skill-atlas/skillSources.generated.ts');
const PREFIX = 'live-tokens-';

const args = process.argv.slice(2);
const write = args.includes('--write');
const check = args.includes('--check');

const skillDirs = readdirSync(SKILLS, { withFileTypes: true })
  .filter((e) => e.isDirectory())
  .map((e) => e.name)
  .sort();

let fileCount = 0;

const skillEntries = skillDirs
  .map((dir) => {
    const id = dir.replace(new RegExp(`^${PREFIX}`), '');
    const skillPath = join(SKILLS, dir);
    const refDir = join(skillPath, 'references');
    const refNames = existsSync(refDir)
      ? readdirSync(refDir).filter((f) => f.endsWith('.md')).sort()
      : [];
    const paths = ['SKILL.md', ...refNames.map((f) => `references/${f}`)];

    const docEntries = paths
      .map((path) => {
        fileCount++;
        const text = readFileSync(join(skillPath, path), 'utf8');
        const lines = text.replace(/\n$/, '').split('\n');
        return `    ${JSON.stringify(path)}: ${JSON.stringify(lines)},`;
      })
      .join('\n');

    return `  ${JSON.stringify(id)}: {\n${docEntries}\n  },`;
  })
  .join('\n');

const next =
  `// AUTOGENERATED by scripts/sync-skill-sources.mjs — do not edit by hand.\n` +
  `// Source of truth: .claude/skills/*/SKILL.md and references/*.md  ·  regenerate: npm run sync:skill-sources\n` +
  `\n` +
  `export const SKILL_DOC = 'SKILL.md' as const;\n` +
  `\n` +
  `export const skillDocs: Record<string, Record<string, string[]>> = {\n${skillEntries}\n};\n`;

const current = readExisting(OUT);
const drifted = current !== next;

if (write) {
  if (drifted) {
    writeFileSync(OUT, next);
    console.log(`WROTE skillSources.generated.ts (${skillDirs.length} skills, ${fileCount} files)`);
  } else {
    console.log(`OK — skillSources.generated.ts already current (${skillDirs.length} skills, ${fileCount} files)`);
  }
} else if (check) {
  if (drifted) {
    console.error(
      `skillSources.generated.ts is out of sync with .claude/skills/*.\n` +
        `Run: npm run sync:skill-sources`,
    );
    process.exit(1);
  }
  console.log(`CHECK — skillSources.generated.ts current (${skillDirs.length} skills, ${fileCount} files)`);
} else {
  console.log(`DRY RUN — ${drifted ? 'DRIFT' : 'clean'} (${skillDirs.length} skills, ${fileCount} files)`);
}

function readExisting(path) {
  try {
    return readFileSync(path, 'utf8');
  } catch {
    return null;
  }
}
